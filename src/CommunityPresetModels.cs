public static class PresetResources
{
    public const int MaxAttachmentBytes = 10 * 1024 * 1024;
    public static readonly string[] Extensions = [".zip", ".7z", ".rar", ".ini", ".json", ".txt", ".cfg", ".fx", ".fxh", ".preset"];
    public static byte[] ValidateAttachment(PresetAttachmentUpload input)
    {
        if (string.IsNullOrWhiteSpace(input.Name) || input.Name.Length > 120 || input.Name != Path.GetFileName(input.Name)
            || input.Name.IndexOfAny(['/', '\\', ':', '<', '>', '"', '|', '?', '*']) >= 0 || input.Name.Any(char.IsControl)
            || input.Name.EndsWith('.') || input.Name.EndsWith(' ') || !Extensions.Contains(Path.GetExtension(input.Name).ToLowerInvariant())
            || string.IsNullOrEmpty(input.Data) || input.Data.Length > (MaxAttachmentBytes + 2) / 3 * 4)
            throw new InvalidDataException("附件格式无效，请上传10 MB以内的压缩包、配置或着色器文件。");
        byte[] bytes;
        try { bytes = Convert.FromBase64String(input.Data); }
        catch (FormatException) { throw new InvalidDataException("附件编码无效。"); }
        if (bytes.Length is < 1 or > MaxAttachmentBytes) throw new InvalidDataException("附件大小须在1字节至10 MB之间。");
        return bytes;
    }
    public static string? ValidateUrl(string? value)
    {
        if (string.IsNullOrWhiteSpace(value)) return null;
        value = value.Trim();
        if (value.Length > 2048 || !Uri.TryCreate(value, UriKind.Absolute, out var uri) || uri.Scheme != "https"
            || uri.HostNameType != UriHostNameType.Dns || !uri.Host.Contains('.') || uri.Host.EndsWith(".local", StringComparison.OrdinalIgnoreCase)
            || uri.Host.EndsWith(".localhost", StringComparison.OrdinalIgnoreCase) || uri.UserInfo.Length > 0 || !uri.IsDefaultPort || value.Any(char.IsControl))
            throw new InvalidDataException("请填写完整的HTTPS网盘链接，不要包含提取码等说明文字。");
        return uri.AbsoluteUri;
    }
}

// Only short scalar settings may leave a game directory. Paths, hooks, binaries and
// process filters remain local and are regenerated by the existing installers.
public static class PresetRules
{
    static readonly Regex Identifier = new("^[A-Za-z][A-Za-z0-9_]{0,39}$", RegexOptions.CultureInvariant);
    static readonly Regex Scalar = new("^(?:true|false|[+-]?[0-9]+(?:\\.[0-9]+)?|[A-Za-z][A-Za-z0-9_-]{0,31})$",
        RegexOptions.CultureInvariant | RegexOptions.IgnoreCase);
    static readonly string[] Forbidden = ["path", "file", "url", "command", "script", "shader", "model", "weight", "proxy", "process", "hook", "log"];
    static readonly HashSet<string> OptiSections = new(StringComparer.OrdinalIgnoreCase)
    { "DlssNr", "FrameGen", "XeFG", "Upscalers", "FSR", "XeSS", "Sharpness", "Quality", "OptiScaler" };
    static readonly HashSet<string> NeuralKeys = new(StringComparer.OrdinalIgnoreCase)
    { "Enabled", "LocalTone", "LocalStructure", "SkinStructure", "UseAutoMask", "ToneChannels",
      "Scale", "Temporal", "Tonemap", "UseFsrInputs", "UseDepth", "Interop", "Inline", "InlineWaitMs" };
    static readonly HashSet<string> IntegratedNrKeys = new(StringComparer.OrdinalIgnoreCase)
    { "Enabled", "RunBeforeSR", "NrBackend", "Passes", "NrInline", "LmxxfEarlyAnyModuleWrap", "LmxxfAllowEnhancedBarriers", "AmdLmxxfFastMode", "AmdLmxxfTierSnap",
      "MochizukiUnlockPasses", "MochizukiPasses", "MochizukiMaxPasses", "MochizukiModelScale", "MochizukiTemporal",
      "MochizukiHistoryStrength", "MochizukiApplyModel", "MochizukiDynamicResolution" };

    public static bool Allowed(int mode, PresetSetting setting)
    {
        if (mode == 6) return setting is not null && setting.File == "OptiScaler.ini" && setting.Section == "DlssNr" &&
            setting.Key != null && IntegratedNrKeys.Contains(setting.Key) && setting.Value != null && Scalar.IsMatch(setting.Value) && setting.Value.Length <= 64;
        if (setting is null || setting.File is null || setting.Section is null || setting.Key is null || setting.Value is null
            || mode is not (0 or 2 or 4) || !Identifier.IsMatch(setting.Section) || !Identifier.IsMatch(setting.Key)
            || !Scalar.IsMatch(setting.Value) || setting.Value.Length > 64
            || Forbidden.Any(part => setting.Key.Contains(part, StringComparison.OrdinalIgnoreCase))) return false;
        if (setting.Section.Equals("ProcessFilter", StringComparison.OrdinalIgnoreCase)
            || setting.Section.Equals("Menu", StringComparison.OrdinalIgnoreCase)
            || setting.Section.Equals("Log", StringComparison.OrdinalIgnoreCase)) return false;
        return mode == 0
            ? setting.File.Equals("dlssnr_on_amd.ini", StringComparison.OrdinalIgnoreCase)
              && setting.Section.Equals("DlssNrOnAmd", StringComparison.OrdinalIgnoreCase)
              && NeuralKeys.Contains(setting.Key)
            : setting.File.Equals("OptiScaler.ini", StringComparison.OrdinalIgnoreCase)
              && OptiSections.Contains(setting.Section);
    }

    public static PresetSetting[] Validate(int mode, IEnumerable<PresetSetting>? settings)
    {
        var array = settings?.ToArray() ?? [];
        if (array.Length is < 1 or > 80 || array.Any(s => s is null || !Allowed(mode, s)))
            throw new InvalidDataException("方案包含不支持的配置项。");
        if (array.GroupBy(s => $"{s.File}/{s.Section}/{s.Key}", StringComparer.OrdinalIgnoreCase).Any(g => g.Count() > 1))
            throw new InvalidDataException("方案包含重复配置项。");
        if (mode == 6)
        {
            var values = array.ToDictionary(s => s.Key, s => s.Value, StringComparer.OrdinalIgnoreCase);
            if (!values.TryGetValue("NrBackend", out var backend) || backend is not ("daniel" or "lmxxf" or "mochizuki")) throw new InvalidDataException("方案缺少有效 NR 后端。");
            foreach (var (key, value) in values)
            {
                if (key == "NrBackend") continue;
                var valid = key switch
                {
                    "Passes" => int.TryParse(value, out var n) && n is >= 1 and <= 3,
                    "MochizukiPasses" => int.TryParse(value, out var n) && n is >= 1 and <= 30,
                    "MochizukiMaxPasses" => int.TryParse(value, out var n) && n == 0,
                    "MochizukiDynamicResolution" => int.TryParse(value, out var n) && n is >= 0 and <= 2,
                    "MochizukiModelScale" => double.TryParse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var n) && double.IsFinite(n) && n is >= .25 and <= 1,
                    "MochizukiHistoryStrength" => double.TryParse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out var n) && double.IsFinite(n) && n is >= 0 and <= 1,
                    "Enabled" or "RunBeforeSR" => value == "true",
                    _ => value is "true" or "false"
                };
                if (!valid) throw new InvalidDataException("神经渲染方案参数越界：" + key);
            }
            if (backend == "mochizuki" && values.TryGetValue("MochizukiPasses", out var passes) && int.Parse(passes) > 3 && values.GetValueOrDefault("MochizukiUnlockPasses") != "true")
                throw new InvalidDataException("超过 3 Pass 必须显式启用实验解锁。");
        }
        return array;
    }

    public static bool VulkanCompatible(int mode, bool vulkan, IEnumerable<PresetSetting> settings) =>
        !vulkan || (mode == 2 && settings.All(s =>
            !s.Section.Equals("FrameGen", StringComparison.OrdinalIgnoreCase) ||
            !s.Key.Equals("Enabled", StringComparison.OrdinalIgnoreCase) &&
            !s.Key.Equals("FGInput", StringComparison.OrdinalIgnoreCase) ||
            s.Value.Equals("false", StringComparison.OrdinalIgnoreCase) ||
            s.Value.Equals("nofg", StringComparison.OrdinalIgnoreCase)));
}
